// Bundles ui/src into the single ESM file Hermes Desktop loads: desktop/plugin.js.
//
// The host evaluates that file from a blob: URL, so relative imports cannot
// resolve and only three specifiers are allowed. Everything else is bundled.
//
// Also bundles the browser page a stable task link opens (ui/src/task-link/dashboard.jsx)
// into dashboard/dist/index.js: a classic script for the Hermes web dashboard, whose
// react and UI primitives come from window.__HERMES_PLUGIN_SDK__ (src/task-link/dashboard/).
// Usage: node build.mjs [--watch]
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import * as esbuild from 'esbuild'

const root = dirname(fileURLToPath(import.meta.url))
const outfile = join(root, '..', 'desktop', 'plugin.js')
const dashboardOutfile = join(root, '..', 'dashboard', 'dist', 'index.js')
const SHIMS = join(root, 'src', 'task-link', 'dashboard')
const HOST_MODULES = ['@hermes/plugin-sdk', 'react', 'react/jsx-runtime']

const options = {
  entryPoints: [join(root, 'src', 'plugin.jsx')],
  outfile,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  jsx: 'automatic',
  // The loader scans source text for import syntax; readable output keeps that scan honest.
  minify: false,
  legalComments: 'none',
  external: HOST_MODULES,
  loader: { '.css': 'text' },
  metafile: true,
  logLevel: 'warning',
  banner: { js: '// Generated by ui/build.mjs from ui/src. Do not edit; run `npm run build` in ui/.' }
}

// Fails the build when the bundle imports anything the host loader refuses.
function checkImports(metafile) {
  const bad = []
  for (const output of Object.values(metafile.outputs)) {
    for (const entry of output.imports) {
      if (!HOST_MODULES.includes(entry.path) || entry.kind !== 'import-statement') {
        bad.push(`${entry.kind} ${entry.path}`)
      }
    }
  }
  // Belt and braces: the loader's own scan works on text.
  const text = readFileSync(outfile, 'utf8')
  for (const match of text.matchAll(/^import[^;]*?from\s*["']([^"']+)["']/gm)) {
    if (!HOST_MODULES.includes(match[1])) bad.push(`text import ${match[1]}`)
  }
  if (/\bimport\s*\(/.test(text)) bad.push('dynamic import()')
  if (bad.length) {
    throw new Error(`desktop/plugin.js imports modules the Hermes loader rejects:\n  ${bad.join('\n  ')}`)
  }
}

// The dashboard bundle must be self-contained: no import, require or dynamic import at all.
function checkDashboard() {
  const text = readFileSync(dashboardOutfile, 'utf8')
  const bad = []
  if (/^\s*import[\s{*]/m.test(text) || /\bimport\s*\(/.test(text)) bad.push('import')
  if (/\brequire\s*\(/.test(text)) bad.push('require()')
  if (/@hermes\/plugin-sdk|from ["']react/.test(text)) bad.push('unresolved host module')
  if (bad.length) throw new Error(`dashboard/dist/index.js is not a self-contained script: ${bad.join(', ')}`)
}

const shimPlugin = {
  name: 'dashboard-shims',
  setup(build) {
    const map = {
      react: 'react.js',
      'react/jsx-runtime': 'jsx-runtime.js',
      '@hermes/plugin-sdk': 'sdk.js'
    }
    build.onResolve({ filter: /^(react|react\/jsx-runtime|@hermes\/plugin-sdk)$/ }, args => ({ path: join(SHIMS, map[args.path]) }))
  }
}

const dashboardOptions = {
  entryPoints: [join(root, 'src', 'task-link', 'dashboard.jsx')],
  outfile: dashboardOutfile,
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2022',
  jsx: 'automatic',
  minify: false,
  legalComments: 'none',
  loader: { '.css': 'text' },
  logLevel: 'warning',
  banner: { js: '// Generated by ui/build.mjs from ui/src/task-link. Do not edit; run `npm run build` in ui/.' }
}

const dashboardReport = {
  name: 'dashboard-report',
  setup(build) {
    build.onEnd(result => {
      if (result.errors.length) return
      try {
        checkDashboard()
        console.log(`built ${dashboardOutfile}`)
      } catch (error) {
        console.error(error.message)
        if (!process.argv.includes('--watch')) process.exitCode = 1
      }
    })
  }
}

const reportPlugin = {
  name: 'report',
  setup(build) {
    build.onEnd(result => {
      if (result.errors.length) return
      try {
        checkImports(result.metafile)
        console.log(`built ${outfile}`)
      } catch (error) {
        console.error(error.message)
        if (!process.argv.includes('--watch')) process.exitCode = 1
      }
    })
  }
}

// Capture-only builds (RK_LINK_STUB=1) answer task-link setup from a labeled stub, for states the
// sandbox can't produce. A normal build must never carry it.
const LINK_STUB = process.env.RK_LINK_STUB === '1'
const linkStubPlugin = {
  name: 'link-setup-stub',
  setup(build) {
    if (LINK_STUB) {
      build.onResolve({ filter: /task-link-setup\.transport\.js$/ }, () => ({ path: join(root, 'src', 'api', 'task-link-setup.stub.js') }))
      return
    }
    build.onEnd(result => {
      if (result.errors.length) return
      if (readFileSync(outfile, 'utf8').includes('__rkLinkStub')) {
        console.error('desktop/plugin.js carries the task-link setup stub; build without RK_LINK_STUB')
        process.exitCode = 1
      }
    })
  }
}

const dashboardBuild = { ...dashboardOptions, plugins: [shimPlugin, dashboardReport] }

if (process.argv.includes('--watch')) {
  const ctx = await esbuild.context({ ...options, plugins: [linkStubPlugin, reportPlugin] })
  const dashboardCtx = await esbuild.context(dashboardBuild)
  await Promise.all([ctx.watch(), dashboardCtx.watch()])
  console.log('watching ui/src')
} else {
  await esbuild.build({ ...options, plugins: [linkStubPlugin, reportPlugin] })
  if (LINK_STUB) console.log('CAPTURE BUILD: task-link setup answers come from the stub (label evidence -stub)')
  await esbuild.build(dashboardBuild)
}
